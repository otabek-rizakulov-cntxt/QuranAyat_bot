"""The tajweed lessons, ready to show, in two tracks (docs/TAJWEED_PLAN.md).

- `qoidalar` (rules): our own lessons, data/tajweed/lessons.uz.json. Each lesson's
  `content_hash` covers everything a reviewer approved (title, body, examples), so
  editing a lesson after approval turns it back into a draft without anyone having
  to remember to reset it (§6).
- `alifbo` (reading): the Muallimi soniy audio lessons, data/tajweed/muallimi.json
  (generated by scripts/tajweed/muallimi.py). Published as they are; the audio
  itself is on R2 under the configured base URL.

Everything is written in Uzbek Latin; `uz-Cyrl` is generated with domain.uz_translit.
"""

import hashlib
import json
import os
from typing import Dict, List, NamedTuple, Optional, Tuple

from domain import tajweed
from domain.uz_translit import to_cyrillic

_DATA = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
    "data",
    "tajweed",
)
_PATH = os.path.join(_DATA, "lessons.uz.json")
_AUDIO_PATH = os.path.join(_DATA, "muallimi.json")
_TEXT_PATH = os.path.join(_DATA, "muallimi_text.txt")
TRACK_AUDIO, TRACK_RULES = "alifbo", "qoidalar"
TRACKS = (TRACK_AUDIO, TRACK_RULES)
AUTO_EXAMPLES = 3  # examples per lesson when the lesson says "auto"
LANGS = ("uz", "uz-Cyrl")

Example = Tuple[int, int, Tuple[str, ...]]  # (surah, ayah, rules to mark)


class Lesson(NamedTuple):
    id: str
    unit: str
    title: str
    rules: Tuple[str, ...]
    body: Tuple[str, ...]  # paragraphs, Telegram HTML subset (<b>, <i>, <u>)
    examples: Tuple[Example, ...]
    content_hash: str


class Unit(NamedTuple):
    id: str
    title: str


class AudioLesson(NamedTuple):
    id: str  # "ms-001"
    unit: str
    n: int  # the lesson's number in the book
    title: str
    file: str  # "001.mp3" under the audio base URL
    bytes: int
    seconds: float
    sha256: str


_cache: Dict[str, Tuple[Tuple[Unit, ...], Tuple[Lesson, ...]]] = {}
_audio_cache: Dict[str, Tuple[Tuple[Unit, ...], Tuple[AudioLesson, ...]]] = {}


def _examples(raw, rules: Tuple[str, ...]) -> Tuple[Example, ...]:
    if raw == "auto":
        out, seen = [], set()
        # Round-robin over the lesson's rules so a two-rule lesson shows both.
        per_rule = [tajweed.examples(r, AUTO_EXAMPLES * 2) for r in rules]
        for i in range(AUTO_EXAMPLES * 2):
            for rule, exs in zip(rules, per_rule):
                if i < len(exs) and exs[i] not in seen and len(out) < AUTO_EXAMPLES:
                    seen.add(exs[i])
                    out.append((exs[i][0], exs[i][1], (rule,)))
        return tuple(out)
    return tuple((s, a, rules) for s, a in raw)


def _hash(lesson: dict, examples: Tuple[Example, ...]) -> str:
    payload = json.dumps(
        [lesson["title"], lesson["body"], [list(e[:2]) + list(e[2]) for e in examples]],
        ensure_ascii=False,
    )
    return hashlib.sha1(payload.encode("utf-8")).hexdigest()[:12]


def _load(lang: str) -> Tuple[Tuple[Unit, ...], Tuple[Lesson, ...]]:
    if lang not in _cache:
        with open(_PATH, encoding="utf-8") as fp:
            raw = json.load(fp)
        tr = to_cyrillic if lang == "uz-Cyrl" else (lambda s: s)
        units = tuple(Unit(u["id"], tr(u["title"])) for u in raw["units"])
        lessons = []
        for item in raw["lessons"]:
            rules = tuple(item["rules"])
            examples = _examples(item["examples"], rules)
            lessons.append(
                Lesson(
                    id=item["id"],
                    unit=item["unit"],
                    title=tr(item["title"]),
                    rules=rules,
                    body=tuple(tr(p) for p in item["body"]),
                    examples=examples,
                    # one hash for both scripts: approval is of the Latin source
                    content_hash=_hash(item, examples),
                )
            )
        _cache[lang] = (units, tuple(lessons))
    return _cache[lang]


def units(lang: str = "uz") -> Tuple[Unit, ...]:
    return _load(lang)[0]


def lessons(lang: str = "uz") -> Tuple[Lesson, ...]:
    return _load(lang)[1]


def lesson(lesson_id: str, lang: str = "uz") -> Optional[Lesson]:
    return next((x for x in lessons(lang) if x.id == lesson_id), None)


def _load_audio(lang: str) -> Tuple[Tuple[Unit, ...], Tuple[AudioLesson, ...]]:
    if lang not in _audio_cache:
        with open(_AUDIO_PATH, encoding="utf-8") as fp:
            raw = json.load(fp)
        tr = to_cyrillic if lang == "uz-Cyrl" else (lambda s: s)
        units = tuple(Unit(u["id"], tr(u["title"])) for u in raw["units"])
        lessons = tuple(
            AudioLesson(
                id=x["id"],
                unit=x["unit"],
                n=x["n"],
                title=tr(x["title"]),
                file=x["file"],
                bytes=x["bytes"],
                seconds=x["seconds"],
                sha256=x["sha256"],
            )
            for x in raw["lessons"]
        )
        _audio_cache[lang] = (units, lessons)
    return _audio_cache[lang]


def audio_units(lang: str = "uz") -> Tuple[Unit, ...]:
    return _load_audio(lang)[0]


def audio_lessons(lang: str = "uz") -> Tuple[AudioLesson, ...]:
    """The audio track in teaching order (the preface first)."""
    return _load_audio(lang)[1]


def audio_lesson(lesson_id: str, lang: str = "uz") -> Optional[AudioLesson]:
    return next((x for x in audio_lessons(lang) if x.id == lesson_id), None)


class TextLine(NamedTuple):
    kind: str  # "ar" (an exercise row, as printed) or "uz" (a line of the narration)
    text: str


_text_cache: Dict[str, Dict[str, Tuple[TextLine, ...]]] = {}


def audio_text(lesson_id: str, lang: str = "uz") -> Tuple[TextLine, ...]:
    """The lines an audio lesson reads (data/tajweed/muallimi_text.txt), empty while
    that lesson has none yet. Arabic rows are never transliterated."""
    if lang not in _text_cache:
        tr = to_cyrillic if lang == "uz-Cyrl" else (lambda s: s)
        lessons: Dict[str, list] = {}
        current = None
        with open(_TEXT_PATH, encoding="utf-8") as fp:
            for raw in fp:
                line = raw.strip()
                if line.startswith("## "):
                    current = lessons.setdefault("ms-%03d" % int(line[3:]), [])
                elif line[:3] in ("ar:", "uz:") and current is not None:
                    kind, text = line[:2], line[3:].strip()
                    current.append(TextLine(kind, text if kind == "ar" else tr(text)))
        _text_cache[lang] = {k: tuple(v) for k, v in lessons.items()}
    return _text_cache[lang].get(lesson_id, ())


def audio_url(lesson: AudioLesson, base: str) -> str:
    return base.rstrip("/") + "/" + lesson.file


def track_of(lesson_id: str) -> Optional[str]:
    """Which track a lesson id belongs to, or None for an unknown id."""
    if audio_lesson(lesson_id) is not None:
        return TRACK_AUDIO
    if lesson(lesson_id) is not None:
        return TRACK_RULES
    return None


def neighbours(lesson_id: str, ids: List[str]) -> Tuple[Optional[str], Optional[str]]:
    """Previous and next lesson ids within `ids` (the lessons this user may see)."""
    if lesson_id not in ids:
        return None, None
    i = ids.index(lesson_id)
    return (ids[i - 1] if i else None), (ids[i + 1] if i + 1 < len(ids) else None)


def reset_for_tests() -> None:
    _cache.clear()
    _audio_cache.clear()
    _text_cache.clear()
